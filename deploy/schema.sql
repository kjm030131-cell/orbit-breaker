CREATE TABLE IF NOT EXISTS players(
  sid TEXT PRIMARY KEY, name TEXT NOT NULL, dept TEXT NOT NULL,
  best INTEGER NOT NULL DEFAULT 0, attempts INTEGER NOT NULL DEFAULT 0,
  kills INTEGER DEFAULT 0, chain INTEGER DEFAULT 0, combo INTEGER DEFAULT 0,
  unit TEXT, frame TEXT, best_at TEXT, created_at TEXT);
CREATE INDEX IF NOT EXISTS idx_players_best ON players(best DESC);
CREATE TABLE IF NOT EXISTS runs(
  id TEXT PRIMARY KEY, sid TEXT NOT NULL, started INTEGER NOT NULL,
  finished INTEGER NOT NULL DEFAULT 0, score INTEGER, unit TEXT, frame TEXT);
CREATE TABLE IF NOT EXISTS boss_kills(
  run_id TEXT PRIMARY KEY, sid TEXT NOT NULL, t REAL NOT NULL, at INTEGER NOT NULL);
